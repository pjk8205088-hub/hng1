function applyLanguage(next) {
  language = normalizeLanguage(next) || 'pt';
  try {
    localStorage.setItem('hng-language', language);
  } catch {
    // Language switching still works when the browser blocks storage.
  }
  document.documentElement.lang = language === 'pt' ? 'pt-BR' : language;
  const copy = I18N[language];
  document.title = copy['page.title'];
  document.querySelector('meta[name="description"]')?.setAttribute('content', copy['page.description']);
  document.querySelector('meta[http-equiv="Content-Language"]')?.setAttribute('content', document.documentElement.lang);

  const url = new URL(location.href);
  url.searchParams.set('lang', language);
  history.replaceState(null, '', url.pathname + url.search + url.hash);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n] ?? I18N.pt[element.dataset.i18n];
    if (value !== undefined) {
      element.textContent = value;
    }
  });

  for (const [attribute, datasetKey] of [['alt', 'i18nAlt'], ['aria-label', 'i18nAria'], ['placeholder', 'i18nPlaceholder']]) {
    const selector = attribute === 'aria-label' ? '[data-i18n-aria]' : `[data-i18n-${attribute}]`;
    document.querySelectorAll(selector).forEach((element) => {
      const value = copy[element.dataset[datasetKey]] ?? I18N.pt[element.dataset[datasetKey]];
      if (value !== undefined) element.setAttribute(attribute, value);
    });
  }

  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === language));
  });

}

function resetDialog() {
  if (form) {
    form.hidden = false;
    form.reset();
    delete form.dataset.plan;
    delete form.dataset.amount;
  }
  if (dialogSuccess) {
    dialogSuccess.hidden = true;
  }
}

