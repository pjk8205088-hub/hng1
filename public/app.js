function normalizeLanguage(value) {
  const key = String(value || '').toLowerCase();
  if (key === 'kr' || key === 'ko-kr') return 'ko';
  if (key === 'pt-br') return 'pt';
  return Object.hasOwn(I18N, key) ? key : null;
}

function savedLanguage() {
  try {
    return normalizeLanguage(localStorage.getItem('hng-language'));
  } catch {
    return null;
  }
}

